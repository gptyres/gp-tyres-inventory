import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const SOURCE_URL = 'https://hoosiertyres.co.za/shop/';
const API_URL = 'https://hoosiertyres.co.za/wp-json/wc/store/v1/products?per_page=100';
const OUTPUT_PATH = path.resolve(process.cwd(), 'supplier_data', 'hoosierData.ts');
const WANTED_CATEGORIES = new Map([
  ['dirt-oval-tyres', 'Dirt Oval Tyres'],
  ['drag-tyres', 'Drag Tyres'],
  ['racing-tyres', 'Racing Tyres'],
  ['pro-street', 'Pro Street']
]);

const cleanText = (value = '') => String(value)
  .replace(/<[^>]*>/g, ' ')
  .replace(/&nbsp;|&#160;/gi, ' ')
  .replace(/&amp;/gi, '&')
  .replace(/&#8211;|&ndash;/gi, '-')
  .replace(/&#8212;|&mdash;/gi, '-')
  .replace(/&#8217;|&rsquo;/gi, "'")
  .replace(/\s+/g, ' ')
  .trim();

const splitProductName = (name) => {
  const normalized = cleanText(name);
  const parts = normalized.split(/\s+[\u2013\u2014]\s+/);
  return {
    pattern: (parts[0] || normalized).replace(/^Hoosier\s+/i, '').trim(),
    size: cleanText(parts.slice(1).join(' - '))
      .replace(/\u00d7/g, 'X')
      .replace(/\s+/g, '')
      .toUpperCase()
  };
};

const parseStockUnits = (availability) => {
  if (availability?.class !== 'in-stock') return 0;
  const match = String(availability?.text || '').match(/(\d+)\s+in\s+stock/i);
  return match ? Number(match[1]) : 0;
};

const parsePrice = (prices) => {
  const minorUnit = Number(prices?.currency_minor_unit ?? 2);
  return Number(prices?.price || 0) / (10 ** minorUnit);
};

const response = await fetch(API_URL, {
  headers: { Accept: 'application/json', 'User-Agent': 'GP-Tyres-Hoosier-Sync/1.0' }
});
if (!response.ok) throw new Error(`Hoosier catalogue request failed (${response.status}).`);

const products = await response.json();
const syncedAt = new Date().toISOString();
const rows = products
  .map((product) => {
    const category = (product.categories || []).find((candidate) => WANTED_CATEGORIES.has(candidate.slug));
    if (!category) return null;
    const { pattern, size } = splitProductName(product.name);
    const stockUnits = parseStockUnits(product.stock_availability);
    return {
      websiteProductId: Number(product.id),
      supplierSku: cleanText(product.sku) || String(product.id),
      brand: 'HOOSIER',
      pattern,
      size,
      category: WANTED_CATEGORIES.get(category.slug),
      productName: cleanText(product.name),
      stockUnits,
      orderStatus: product.stock_availability?.class === 'in-stock' ? 'AVAILABLE' : 'PREORDER',
      websiteStockDetail: cleanText(product.stock_availability?.text),
      sellingPrice: parsePrice(product.prices),
      imageUrl: cleanText(product.images?.[0]?.src),
      sourceUrl: cleanText(product.permalink)
    };
  })
  .filter(Boolean)
  .sort((left, right) => (
    [...WANTED_CATEGORIES.values()].indexOf(left.category) - [...WANTED_CATEGORIES.values()].indexOf(right.category)
    || left.pattern.localeCompare(right.pattern)
    || left.size.localeCompare(right.size, undefined, { numeric: true })
  ));

if (rows.length !== 58) throw new Error(`Expected 58 Hoosier products, received ${rows.length}.`);
if (new Set(rows.map((row) => row.supplierSku)).size !== rows.length) {
  throw new Error('Duplicate Hoosier supplier SKUs were detected.');
}
if (rows.some((row) => !row.pattern || !row.size || row.sellingPrice <= 0)) {
  throw new Error('A Hoosier product is missing pattern, size, or price data.');
}

const source = `// Generated by scripts/sync-hoosier-catalog.mjs from the official Hoosier South Africa WooCommerce Store API.\n`
  + `// Source: ${SOURCE_URL}\n`
  + `// Synced: ${syncedAt}\n\n`
  + `export const HOOSIER_CATALOG_SOURCE_URL = ${JSON.stringify(SOURCE_URL)};\n`
  + `export const HOOSIER_CATALOG_SYNCED_AT = ${JSON.stringify(syncedAt)};\n`
  + `export const HOOSIER_ROWS = ${JSON.stringify(rows, null, 2)} as const;\n`;

await mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
await writeFile(OUTPUT_PATH, source, 'utf8');

const counts = Object.fromEntries([...WANTED_CATEGORIES.values()].map((category) => [
  category,
  rows.filter((row) => row.category === category).length
]));
console.log(JSON.stringify({
  output: OUTPUT_PATH,
  rows: rows.length,
  available: rows.filter((row) => row.orderStatus === 'AVAILABLE').length,
  preorder: rows.filter((row) => row.orderStatus === 'PREORDER').length,
  stockUnits: rows.reduce((total, row) => total + row.stockUnits, 0),
  counts
}, null, 2));
