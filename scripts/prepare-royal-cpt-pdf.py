    parser = argparse.ArgumentParser()
    parser.add_argument('pdf')
    parser.add_argument('--out', default='reports/royal-cpt-extracted.json')
    parser.add_argument('--baseline', required=True, help='Export from the existing Royal workbook publisher')
    args = parser.parse_args()
    rows = extract(args.pdf)
    baseline = json.loads(Path(args.baseline).read_text(encoding='utf-8'))
    normalize = lambda text: re.sub(r'[^A-Z0-9]', '', text.upper())
    for row in rows:
        # The PDF uses both Pirelli/Prometeon logos and places three Road-Buster
        # H108CE products under RockBuster. Retain their existing SKU/brand identity.
        brand = row['brand']
        if brand == 'PROMETEON':
            brand = 'PIRELLI PROMETEON'
        elif brand == 'ROCKBUSTER' and 'H108CE' in row['description']:
            brand = 'ROAD-BUSTER'
        key = normalize(brand + ' ' + row['description'])
        matches = [item for item in baseline if normalize(item['product_name']) == key]
        if len(matches) > 1:
            raise ValueError(f'Ambiguous match: {row}')
        if matches:
            original = matches[0]
            row.update(source_key=original['source_key'], sku=original['supplier_sku'],
                       before_units=original['stock_by_location']['CPT'], before_cost=original['cost_price'],
                       matched_name=original['product_name'])
        else:
            if row['brand'] != 'ANCHEE' or row['description'] != '195/60R15 (H/T) 88H AC808':
                raise ValueError(f'Unreviewed new product: {row}')
            row.update(source_key='royal-cpt-anchee-195-60r15-ac808-88h', sku='',
                       before_units=0, before_cost=None, matched_name=None)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(dict(source_file=Path(args.pdf).name,
                                   sha256=hashlib.sha256(Path(args.pdf).read_bytes()).hexdigest(),
                                   rows=rows), indent=2)+'\n', encoding='utf-8')
