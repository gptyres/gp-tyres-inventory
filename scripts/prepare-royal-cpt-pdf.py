"""Extract the visually reviewed September CPT tyre tables, excluding the rims page."""
import argparse
import hashlib
import json
import re
from pathlib import Path
from pypdf import PdfReader

SECTIONS = [
    [('ANCHEE', 36)],
    [('SAILUN', 12), ('SONIX', 1), ('ANNAITE', 2)],
    [('ACCELUS', 13), ('FIREMAX', 8)],
    [('PIRELLI', 13), ('POWERTRAC', 2), ('HABILEAD', 12)],
    [('PROMETEON', 8), ('TAITONG', 9), ('MACROYAL', 2), ('ANCHEE', 2), ('DOUPRO', 1)],
    [('SUMITOMO', 1)],
    [('AEOLUS', 7), ('TECHHERO', 2), ('ROCKBUSTER', 9), ('ASCENSO', 3), ('ADVANCE', 1)],
    [('LUHE', 1)],
]

def extract(path):
    pdf = PdfReader(path)
    if len(pdf.pages) != 9:
        raise ValueError('Expected the reviewed nine-page September PDF')
    rows = []
    for page, sections in zip(pdf.pages, SECTIONS):
        lines = [m.groups() for line in page.extract_text().splitlines()
                 if (m := re.fullmatch(r'(\d.*\S)\s+(\d+)\s+R([\d,]+(?:\.\d+)?)', line.strip()))]
        if len(lines) != sum(count for _, count in sections):
            raise ValueError(f'Unexpected row count on page {len(rows)}: {len(lines)}')
        offset = 0
        for brand, count in sections:
            for description, units, price in lines[offset:offset+count]:
                rows.append(dict(brand=brand, description=description.upper(),
                                 size=description.split()[0].upper(), units=int(units),
                                 cost=float(price.replace(',', '')), page=pdf.pages.index(page)+1))
            offset += count
    return rows

